"""initial schema from the ORM metadata + PostgreSQL hardening (design 6.1, 10)

Revision ID: 0001
Revises:
Create Date: 2026-10-08

Tables, indexes and CHECK constraints come from ``acvm.db.tables.Base.metadata`` (the single source of truth).
PostgreSQL-only hardening is applied when the dialect is ``postgresql``:

* ``CREATE EXTENSION vector`` (before the tables — ``embedding`` columns are ``vector(1024)``)
* ``affiliate_link`` append-only: UPDATE of identity/attribution columns, DELETE and TRUNCATE are rejected;
  only ``health``/``checked_at`` may change (link-swap defence, §10 링크 무결성)
* ``audit_log`` append-only: UPDATE/TRUNCATE always rejected, DELETE only inside a transaction that ran
  ``SET LOCAL acvm.retention = 'on'`` (the 1-year retention job, §10 감사)
* HNSW ANN indexes (cosine) on ``content_dna``, ``content``, ``playbook_rule`` embeddings
* BRIN index on ``audit_log(at)`` (append-only, time-ordered → tiny index for range scans)

Schema-evolution rule: this revision is metadata-driven only until the first production upgrade (gate G0).
From then on every ORM change ships as a new autogenerated revision (``alembic revision --autogenerate``);
``tests/unit/test_ops_migrations.py`` fails when the ORM and the migrated schema drift apart.
"""

from __future__ import annotations

from collections.abc import Sequence

from alembic import op
from sqlalchemy.schema import CreateIndex, CreateTable, DropTable

from acvm.db.tables import Base

revision: str = "0001"
down_revision: str | Sequence[str] | None = None
branch_labels: str | Sequence[str] | None = None
depends_on: str | Sequence[str] | None = None

#: affiliate_link columns that may never change after insert (design §10). health/checked_at stay mutable.
LINK_IMMUTABLE_COLUMNS: tuple[str, ...] = (
    "id", "product_id", "sub_id", "deeplink", "short_url", "hub_code", "signature", "publication_key", "created_at",
)
#: tables whose ``embedding vector(1024)`` column gets an HNSW cosine index.
HNSW_TABLES: tuple[str, ...] = ("content_dna", "content", "playbook_rule")
HNSW_M = 16
HNSW_EF_CONSTRUCTION = 64


def _is_postgres() -> bool:
    return op.get_context().dialect.name == "postgresql"


def _link_guard_sql() -> str:
    changed = "\n        OR ".join(f"NEW.{col} IS DISTINCT FROM OLD.{col}" for col in LINK_IMMUTABLE_COLUMNS)
    # No '%' (driver paramstyles) and no ':word' (bind-param syntax) in these bodies — they are emitted verbatim.
    return f"""
CREATE OR REPLACE FUNCTION acvm_affiliate_link_guard() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP IN ('DELETE', 'TRUNCATE') THEN
        RAISE EXCEPTION USING
            MESSAGE = 'affiliate_link is append-only (design section 10) - ' || TG_OP || ' rejected',
            ERRCODE = 'insufficient_privilege';
    END IF;
    IF {changed} THEN
        RAISE EXCEPTION USING
            MESSAGE = 'affiliate_link immutable column update rejected (only health/checked_at may change)',
            ERRCODE = 'insufficient_privilege';
    END IF;
    RETURN NEW;
END
$$
""".strip()


AUDIT_GUARD_SQL = """
CREATE OR REPLACE FUNCTION acvm_audit_log_guard() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP = 'DELETE' AND coalesce(current_setting('acvm.retention', true), 'off') = 'on' THEN
        RETURN OLD;
    END IF;
    IF TG_OP = 'DELETE' THEN
        RAISE EXCEPTION USING
            MESSAGE = 'audit_log is append-only - DELETE rejected',
            HINT = 'only the retention job may delete, after SET LOCAL acvm.retention = ''on''',
            ERRCODE = 'insufficient_privilege';
    END IF;
    RAISE EXCEPTION USING
        MESSAGE = 'audit_log is append-only - ' || TG_OP || ' rejected',
        ERRCODE = 'insufficient_privilege';
END
$$
""".strip()


def _postgres_hardening() -> list[str]:
    stmts = [
        _link_guard_sql(),
        "CREATE TRIGGER trg_affiliate_link_append_only BEFORE UPDATE OR DELETE ON affiliate_link "
        "FOR EACH ROW EXECUTE FUNCTION acvm_affiliate_link_guard()",
        "CREATE TRIGGER trg_affiliate_link_no_truncate BEFORE TRUNCATE ON affiliate_link "
        "FOR EACH STATEMENT EXECUTE FUNCTION acvm_affiliate_link_guard()",
        AUDIT_GUARD_SQL,
        "CREATE TRIGGER trg_audit_log_append_only BEFORE UPDATE OR DELETE ON audit_log "
        "FOR EACH ROW EXECUTE FUNCTION acvm_audit_log_guard()",
        "CREATE TRIGGER trg_audit_log_no_truncate BEFORE TRUNCATE ON audit_log "
        "FOR EACH STATEMENT EXECUTE FUNCTION acvm_audit_log_guard()",
        "COMMENT ON TABLE affiliate_link IS 'append-only: identity/attribution columns immutable (design section 10)'",
        "COMMENT ON TABLE audit_log IS 'append-only: DELETE only by the retention job (acvm.retention=on)'",
    ]
    stmts += [
        f"CREATE INDEX IF NOT EXISTS ix_{table}_embedding_hnsw ON {table} "
        f"USING hnsw (embedding vector_cosine_ops) WITH (m = {HNSW_M}, ef_construction = {HNSW_EF_CONSTRUCTION})"
        for table in HNSW_TABLES
    ]
    stmts.append("CREATE INDEX IF NOT EXISTS ix_audit_log_at_brin ON audit_log USING brin (at) "
                 "WITH (pages_per_range = 32)")
    return stmts


def upgrade() -> None:
    postgres = _is_postgres()
    if postgres:
        op.execute("CREATE EXTENSION IF NOT EXISTS vector")
    for table in Base.metadata.sorted_tables:
        op.execute(CreateTable(table))
        for index in sorted(table.indexes, key=lambda ix: ix.name or ""):
            op.execute(CreateIndex(index))
    if postgres:
        for stmt in _postgres_hardening():
            op.execute(stmt)


def downgrade() -> None:
    if _is_postgres():
        for table in HNSW_TABLES:
            op.execute(f"DROP INDEX IF EXISTS ix_{table}_embedding_hnsw")
        op.execute("DROP INDEX IF EXISTS ix_audit_log_at_brin")
        for trigger, table in (
            ("trg_affiliate_link_append_only", "affiliate_link"),
            ("trg_affiliate_link_no_truncate", "affiliate_link"),
            ("trg_audit_log_append_only", "audit_log"),
            ("trg_audit_log_no_truncate", "audit_log"),
        ):
            op.execute(f"DROP TRIGGER IF EXISTS {trigger} ON {table}")
        op.execute("DROP FUNCTION IF EXISTS acvm_affiliate_link_guard()")
        op.execute("DROP FUNCTION IF EXISTS acvm_audit_log_guard()")
        # The vector extension is left installed: it is database-level and may be shared.
    for table in reversed(Base.metadata.sorted_tables):
        op.execute(DropTable(table, if_exists=True))
