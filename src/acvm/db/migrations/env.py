"""Alembic environment — async engine, ORM metadata as the single source of truth.

URL precedence: ``-x url=...`` > ``sqlalchemy.url`` (programmatic callers) > ``ACVM_DATABASE_URL`` >
``acvm.config.Settings().database_url``. Offline mode (``--sql``) renders DDL for the URL's dialect without
connecting, which is how the PostgreSQL hardening is reviewed and tested without a server.
"""

from __future__ import annotations

import asyncio
import os
import threading
from collections.abc import Coroutine
from logging.config import fileConfig
from typing import Any

from alembic import context
from sqlalchemy import Connection, create_engine, pool
from sqlalchemy.engine import make_url
from sqlalchemy.ext.asyncio import create_async_engine

from acvm.db.tables import Base

config = context.config

if config.config_file_name is not None and config.attributes.get("configure_logger", True):
    fileConfig(config.config_file_name, disable_existing_loggers=False)

target_metadata = Base.metadata


def _database_url() -> str:
    override = context.get_x_argument(as_dictionary=True).get("url")
    if override:
        return override
    configured = config.get_main_option("sqlalchemy.url")
    if configured:
        return configured
    env = os.environ.get("ACVM_DATABASE_URL")
    if env:
        return env
    from acvm.config import Settings

    return Settings().database_url


def _include_object(obj: Any, name: str | None, type_: str, reflected: bool, compare_to: Any) -> bool:
    # Tables owned outside the ORM (e.g. the SQL perf-store fallback) must never be autogenerated away.
    return not (type_ == "table" and reflected and compare_to is None)


def _configure_kwargs(dialect_name: str) -> dict[str, Any]:
    return {
        "target_metadata": target_metadata,
        "compare_type": True,
        "include_object": _include_object,
        "render_as_batch": dialect_name == "sqlite",  # SQLite ALTER support via table rebuild
        "transaction_per_migration": True,
    }


def run_migrations_offline() -> None:
    url = make_url(_database_url())
    context.configure(url=url, literal_binds=True, dialect_opts={"paramstyle": "named"},
                      **_configure_kwargs(url.get_backend_name()))
    with context.begin_transaction():
        context.run_migrations()


def _run_with_connection(connection: Connection) -> None:
    context.configure(connection=connection, **_configure_kwargs(connection.dialect.name))
    with context.begin_transaction():
        context.run_migrations()


async def _run_async(url: str) -> None:
    engine = create_async_engine(url, poolclass=pool.NullPool)
    try:
        async with engine.connect() as connection:
            await connection.run_sync(_run_with_connection)
    finally:
        await engine.dispose()


def _run_coroutine(coro: Coroutine[Any, Any, None]) -> None:
    """asyncio.run, or a helper thread when called from inside a running loop (async CLI, pytest-asyncio)."""
    try:
        asyncio.get_running_loop()
    except RuntimeError:
        asyncio.run(coro)
        return
    failure: list[BaseException] = []

    def _target() -> None:
        try:
            asyncio.run(coro)
        except BaseException as exc:  # re-raised in the caller's thread
            failure.append(exc)

    worker = threading.Thread(target=_target, name="alembic-migrate")
    worker.start()
    worker.join()
    if failure:
        raise failure[0]


def run_migrations_online() -> None:
    supplied = config.attributes.get("connection")
    if supplied is not None:  # caller already holds a (sync) connection
        _run_with_connection(supplied)
        return
    url = _database_url()
    if make_url(url).get_dialect().is_async:
        _run_coroutine(_run_async(url))
        return
    engine = create_engine(url, poolclass=pool.NullPool)
    try:
        with engine.connect() as connection:
            _run_with_connection(connection)
    finally:
        engine.dispose()


if context.is_offline_mode():
    run_migrations_offline()
else:
    run_migrations_online()
